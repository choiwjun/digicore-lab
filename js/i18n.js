// Current language (default: Korean)
let currentLang = localStorage.getItem('digicore-lang') || 'ko';

// Initialize i18n
document.addEventListener('DOMContentLoaded', function() {
  initLanguageSwitcher();
  applyTranslations(currentLang);
});

// Language Switcher
function initLanguageSwitcher() {
  const langButtons = document.querySelectorAll('.lang-btn');

  langButtons.forEach(btn => {
    // Set active state based on current language
    if (btn.dataset.lang === currentLang) {
      btn.classList.add('active');
    }

    btn.addEventListener('click', function() {
      const selectedLang = this.dataset.lang;

      if (selectedLang === currentLang) return;

      // Update active state
      langButtons.forEach(b => b.classList.remove('active'));
      this.classList.add('active');

      // Apply translations
      currentLang = selectedLang;
      localStorage.setItem('digicore-lang', selectedLang);
      applyTranslations(selectedLang);

      // Update HTML lang attribute
      document.documentElement.lang = selectedLang === 'ko' ? 'ko' : 'ja';
    });
  });
}

// Apply Translations
function applyTranslations(lang) {
  const elements = document.querySelectorAll('[data-i18n]');

  elements.forEach(element => {
    const key = element.dataset.i18n;
    const translation = translations[lang][key];

    if (translation) {
      // Handle multiline text (like footer description)
      if (translation.includes('\n')) {
        element.innerHTML = translation.replace(/\n/g, '<br>');
      } else {
        element.textContent = translation;
      }
    }
  });
}

// Get translation by key
function t(key) {
  return translations[currentLang][key] || key;
}

// Get current language
function getCurrentLang() {
  return currentLang;
}

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    t,
    getCurrentLang,
    applyTranslations
  };
}
